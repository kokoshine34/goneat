let activeProduct = "flights";
let activeLanguage = localStorage.getItem("goEatLanguage") || "en";
const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];

function setLanguage(language) {
  activeLanguage = translations[language] ? language : "en";
  localStorage.setItem("goEatLanguage", activeLanguage);
  document.documentElement.lang = activeLanguage === "my" ? "my" : "en";
  document.body.classList.toggle("lang-my", activeLanguage === "my");
  $("#language-select").value = activeLanguage;
  $$("[data-i18n]").forEach(el => {
    const value = translations[activeLanguage][el.dataset.i18n];
    if (value) el.innerHTML = value;
  });
}
function setProduct(product) {
  activeProduct = product;
  $$(".booking-tab").forEach(tab => {
    const selected = tab.dataset.tab === product;
    tab.classList.toggle("active", selected);
    tab.setAttribute("aria-selected", String(selected));
  });
  ["flights","hotels","attractions","trains"].forEach(name => {
    const panel = $("#" + (name === "flights" ? "flight" : name === "hotels" ? "hotel" : name === "attractions" ? "attraction" : "train") + "-fields");
    panel.classList.toggle("hidden", name !== product);
    panel.querySelectorAll("input,select").forEach(input => input.required = name === product && input.dataset.optional !== "true");
  });
}
function makePartnerOption(provider, url) {
  const a = document.createElement("a");
  a.className = "partner-option";
  a.href = url;
  a.target = "_blank";
  a.rel = "sponsored nofollow noopener noreferrer";
  a.innerHTML = `<strong>${provider}</strong><span>Continue ↗</span>`;
  a.addEventListener("click", () => {
    window.dispatchEvent(new CustomEvent("goeat:affiliate-click", {detail:{provider, product:activeProduct, language:activeLanguage}}));
  });
  return a;
}
function openPartnerModal() {
  const config = window.GO_EAT_AFFILIATES || {};
  const partners = activeProduct === "hotels"
    ? [{name:"Trip.com",url:config.tripcom?.hotels},{name:"Agoda",url:config.agoda?.hotels}]
    : [{name:"Trip.com",url:config.tripcom?.[activeProduct]}];
  const available = partners.filter(p => typeof p.url === "string" && p.url.trim() !== "");
  const box = $("#partner-options");
  box.replaceChildren();
  if (!available.length) {
    $("#modal-title").textContent = activeLanguage === "my" ? "Affiliate လင့်ခ် ထည့်သွင်းရန် လိုအပ်ပါသည်" : "Partner links need to be configured";
    $("#modal-copy").textContent = activeLanguage === "my"
      ? "သင့်ရဲ့ Trip.com သို့မဟုတ် Agoda Partner Dashboard မှ ထုတ်ပေးထားသော affiliate link ကို affiliate-config.js ထဲတွင် ထည့်သွင်းပါ။"
      : "Add the exact affiliate URL generated in your Trip.com or Agoda Partner Dashboard to affiliate-config.js. No untracked booking link will be shown.";
    $("#integration-note").textContent = activeLanguage === "my" ? "သင့်ရဲ့ affiliate လင့်ခ်များကို ထည့်သွင်းပြီးနောက် ရှာဖွေမှုကို အသုံးပြုနိုင်ပါမည်။" : "Affiliate links are not configured yet. Add your approved partner links to enable booking.";
  } else {
    $("#modal-title").textContent = activeLanguage === "my" ? "မိတ်ဖက်ဝက်ဘ်ဆိုက်တွင် ဆက်လက်လုပ်ဆောင်ရန်" : "Continue with our partner";
    $("#modal-copy").textContent = activeLanguage === "my" ? "ရွေးချယ်ထားသော ဝန်ဆောင်မှုပေးသူ၏ ဝက်ဘ်ဆိုက်တွင် ဘွတ်ကင်ကို အပြီးသတ်ပါ။" : "Choose a provider. Your booking and payment will be completed on its website.";
    available.forEach(p => box.appendChild(makePartnerOption(p.name,p.url)));
  }
  $("#partner-modal").classList.remove("hidden");
}
$("#language-select").addEventListener("change", e => setLanguage(e.target.value));
$("#menu-toggle").addEventListener("click", () => {
  const nav = $("#main-nav");
  const opened = nav.classList.toggle("open");
  $("#menu-toggle").setAttribute("aria-expanded", String(opened));
});
$$(".main-nav a").forEach(a => a.addEventListener("click", () => $("#main-nav").classList.remove("open")));
$$(".booking-tab").forEach(tab => tab.addEventListener("click", () => setProduct(tab.dataset.tab)));
$("#search-form").addEventListener("submit", e => {
  e.preventDefault();
  const form = e.currentTarget;
  if (!form.reportValidity()) return;
  openPartnerModal();
});
$("#modal-close").addEventListener("click", () => $("#partner-modal").classList.add("hidden"));
$("#partner-modal").addEventListener("click", e => { if (e.target.id === "partner-modal") e.currentTarget.classList.add("hidden"); });
